package runner

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/bilhasry/merapi/internal/spec"
	"github.com/bilhasry/merapi/internal/templ"
)

// ScaffoldOptions configures test generation from the OpenAPI document.
type ScaffoldOptions struct {
	Method string // empty = every method
	Path   string // empty = all paths (prefix match)
	Force  bool   // overwrite existing test files
}

// ScaffoldResult reports one generated (or skipped) file.
type ScaffoldResult struct {
	File    string `json:"file"`
	Method  string `json:"method"`
	Path    string `json:"path"`
	Skipped bool   `json:"skipped"`
	Reason  string `json:"reason,omitempty"`
}

// ScaffoldTest builds a starter scenario for one endpoint and writes it into
// the tests directory.
func ScaffoldTest(ep *spec.Endpoint, testsDir string, force bool) (*ScaffoldResult, error) {
	sc, fileName := scenarioFor(ep)
	path := filepath.Join(testsDir, fileName)
	if _, err := os.Stat(path); err == nil && !force {
		return &ScaffoldResult{File: path, Method: ep.Method, Path: ep.Path, Skipped: true, Reason: "already exists (use --force)"}, nil
	}
	body, err := yamlMarshal(sc)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("# Test scenario for %s %s\n# Generated by `merapi test scaffold` — edit freely.\n",
		strings.ToUpper(ep.Method), ep.Path)
	if vars := usedVariables(sc); len(vars) > 0 {
		header += fmt.Sprintf("#\n# This test needs variables: %s\n# Set them with:  merapi var set <name> <value>\n",
			strings.Join(vars, ", "))
	}
	if err := os.MkdirAll(testsDir, 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(path, append([]byte(header+"\n"), body...), 0o644); err != nil {
		return nil, err
	}
	return &ScaffoldResult{File: path, Method: ep.Method, Path: ep.Path}, nil
}

// ScaffoldAll generates starter tests for every matching endpoint.
func ScaffoldAll(doc *spec.Document, testsDir string, opts ScaffoldOptions) ([]ScaffoldResult, error) {
	var out []ScaffoldResult
	for _, summary := range doc.ListEndpoints(spec.EndpointFilter{PathPrefix: opts.Path}) {
		if opts.Method != "" && !strings.EqualFold(summary.Method, opts.Method) {
			continue
		}
		ep := doc.GetEndpoint(summary.Method, summary.Path)
		if ep == nil {
			continue
		}
		res, err := ScaffoldTest(ep, testsDir, opts.Force)
		if err != nil {
			return out, err
		}
		out = append(out, *res)
	}
	return out, nil
}

// scenarioFor derives a starter scenario from an endpoint definition.
func scenarioFor(ep *spec.Endpoint) (*Scenario, string) {
	method := strings.ToUpper(ep.Method)
	sc := &Scenario{
		Name: method + " " + ep.Path,
		Steps: []Step{{
			Name: "request",
			Request: Request{
				Method:  method,
				Path:    specPathToTemplate(ep.Path),
				Headers: map[string]string{},
			},
		}},
	}
	step := &sc.Steps[0]

	// Request body: prefer a documented example.
	if ep.RequestBody != nil {
		if ct := ep.RequestBody.ContentType; ct != "" && ct != "application/json" {
			step.Request.Headers["Content-Type"] = ct
		}
		if ep.RequestBody.Example != nil {
			step.Request.Json = ep.RequestBody.Example
		} else {
			step.Request.Json = map[string]any{}
		}
	}
	if len(step.Request.Headers) == 0 {
		step.Request.Headers = nil
	}

	// Expected status: first documented 2xx response, else 200.
	status := 0
	var codes []string
	for code := range ep.Responses {
		codes = append(codes, code)
	}
	sort.Strings(codes)
	for _, code := range codes {
		if strings.HasPrefix(code, "2") && code != "default" {
			fmt.Sscanf(code, "%d", &status)
			break
		}
	}
	if status == 0 {
		status = 200
	}
	step.Expect.Status = status

	// Content-type assertion when the expected response documents JSON.
	for _, code := range codes {
		if code == fmt.Sprintf("%d", status) {
			if ct := ep.Responses[code].ContentType; strings.Contains(ct, "json") {
				step.Expect.Headers = map[string]string{"Content-Type": ct}
			}
			break
		}
	}
	return sc, testFileName(ep.Method, ep.Path)
}

// specPathToTemplate turns /pets/{id} into /pets/{{id}} for requests.
func specPathToTemplate(p string) string {
	var b strings.Builder
	i := 0
	for i < len(p) {
		if p[i] == '{' {
			if end := strings.IndexByte(p[i:], '}'); end > 0 {
				b.WriteString("{{")
				b.WriteString(p[i+1 : i+end])
				b.WriteString("}}")
				i += end + 1
				continue
			}
		}
		b.WriteByte(p[i])
		i++
	}
	return b.String()
}

// usedVariables lists template references the scenario depends on.
func usedVariables(sc *Scenario) []string {
	seen := map[string]bool{}
	walk := func(s string) {
		for _, ref := range templ.References(s) {
			if ref == "base_url" || strings.HasPrefix(ref, "secret:") {
				continue
			}
			seen[ref] = true
		}
	}
	for _, step := range sc.Steps {
		walk(step.Request.Path)
		for _, v := range step.Request.Headers {
			walk(v)
		}
		for _, v := range step.Request.Query {
			walk(v)
		}
		walk(step.Request.Body)
		if step.Request.Json != nil {
			if data, err := yamlMarshal(step.Request.Json); err == nil {
				walk(string(data))
			}
		}
	}
	out := make([]string, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func testFileName(method, path string) string {
	p := strings.Trim(path, "/")
	p = strings.NewReplacer("/", "-", "{", "", "}", "").Replace(p)
	p = Slug(p)
	if p == "" {
		p = "root"
	}
	return strings.ToLower(method) + "-" + p + ".yaml"
}
